const I18nContext = createContext({
  lang: 'en',
  changeLang: () => {},
  t: (k, fb) => fb || k,
});

export function I18nProvider({ children }) {
  const [lang, setLang] = useState('en');

  useEffect(() => {
    // Initial load from localStorage
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('margsetu_lang');
      if (saved && (saved === 'en' || saved === 'hi' || saved === 'as')) {
        setLang(saved);
        document.documentElement.lang = saved;
      }
    }

    const handleLangChange = (e) => {
      const newLang = e.detail?.lang || localStorage.getItem('margsetu_lang') || 'en';
      if (newLang === 'en' || newLang === 'hi' || newLang === 'as') {
        setLang(newLang);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = newLang;
        }
      }
    };

    window.addEventListener('margsetu-lang-change', handleLangChange);
    return () => window.removeEventListener('margsetu-lang-change', handleLangChange);
  }, []);

  const changeLang = useCallback((newLang) => {
    if (newLang === 'en' || newLang === 'hi' || newLang === 'as') {
      setLang(newLang);
      if (typeof window !== 'undefined') {
        localStorage.setItem('margsetu_lang', newLang);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = newLang;
        }
        window.dispatchEvent(new CustomEvent('margsetu-lang-change', { detail: { lang: newLang } }));
      }
    }
  }, []);

  const t = useCallback(
    (key, fallback = '') => {
      return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? fallback ?? key;
    },
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, changeLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(I18nContext);
  if (context && context.changeLang) {
    return context;
  }

  // Standalone fallback if rendered outside provider
  return {
    lang: 'en',
    changeLang: () => {},
    t: (key, fallback = '') => TRANSLATIONS.en[key] ?? fallback ?? key,
  };
}
